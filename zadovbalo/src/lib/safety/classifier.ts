import { normalizeForMatching } from "./normalize";
import type { SafetyAssessment, SafetyReason } from "./types";

/**
 * Перший, детермінований шар безпеки. Працює ДО будь-якого AI й не залежить від провайдера.
 * Свідомо обережний: краще зайвий раз показати спокійний екран допомоги, ніж запустити гру.
 * Текст спершу нормалізується (normalizeForMatching): нижній регістр, без апострофів.
 */

// `\b` у JS не бачить кирилицю навіть з прапорцем `u`, тому межі слова задаємо через \p{L}.
const W = "(?<![\\p{L}\\p{N}])";
const E = "(?![\\p{L}\\p{N}])";
const re = (source: string) => new RegExp(source.replaceAll("<", W).replaceAll(">", E), "u");

// Намір нашкодити собі — завжди crisis.
const SELF_HARM: RegExp[] = [
  re("<(покінчити|покінчу|покончить|покончу) (з|с) (собою|життям|жизнью)>"),
  re("<(вбити|вбю|убити|убю|убить|убью) себе>"),
  re("<себе (вбити|вбю|убити|убить|убью)>"),
  re("<(накласти на себе руки|наложить на себя руки)>"),
  re("<не хочу (більше |больше )?(жити|жить|існувати)>"),
  re("<хочу (вмерти|померти|умереть|помереть|здохнути|сдохнуть)>"),
  re("<(краще|лучше) б (я )?(вмерла|вмер|померла|помер|умерла|умер|не жив|не жила|не жил)>"),
  re("<(суїцид|суицид|самогубств|самоубийств)"),
  re("<(порізати|порізала|порізав|порізати собі|порезать|порезала|порезал) (собі |себе |себе )?(вени|руки|себе)>"),
  re("<(наковтатися|наковтаюся|наглотаться|наглотаюсь) (таблеток|пігулок)>"),
  re("<(стрибнути|стрибну|прыгнуть|прыгну|скинутися|скинусь|кинутися|кинусь) (з|с|під|под) (даху|мосту|вікна|крыши|моста|окна|потяг|поезд|машину)>"),
  re("<(не бачу сенсу жити|немає сенсу жити|нема сенсу жити|нет смысла жить)>"),
  re("<(kill myself|end my life|suicide|want to die|hurt myself)>"),
];

// Дієслова тяжкої шкоди (без «себе» — це вже SELF_HARM).
const HARM_VERB = re(
  "<(вбю|убю|убью|вбити|убити|убить|прибю|прибью|заріжу|зарежу|застрелю|пристрелю|підпалю|подожгу|отрую|отравлю|покалічу|покалечу|задушу)>",
);

// Ознаки конкретики. «ніж» без відмінка не беремо: в українській це ще й «than».
const WEAPON = re(
  "<(ножем|ножа|ножі|ножик\\p{L}*|ножом|пістолет\\p{L}*|пистолет\\p{L}*|рушниц\\p{L}*|ружь\\p{L}*|зброя|зброю|зброєю|оружие|оружием|сокир\\p{L}*|топор\\p{L}*|отрут\\p{L}*|ядом|кислот\\p{L}*|гранат\\p{L}*)>",
);
const PLAN = re(
  "<(вже купив|вже купила|уже купил|уже купила|знаю де (він|вона|вони) живе|знаю где (он|она|они) живет|чекатиму на|підстережу|підстерегу|сьогодні вночі|сегодня ночью|завтра вранці|завтра утром|є план|маю план|есть план|все продумав|все продумала|все продумал)>",
);

// Негайна небезпека для самої людини.
const IMMEDIATE_DANGER: RegExp[] = [
  re("<(він|вона|вони|чоловік|дружина|батько|мати|он|она|они|муж|жена|отец|мать) (мене|меня) (бє|бють|бьет|бьют|душить|душит)>"),
  re("<(мене|меня) (зараз |сейчас )?(бють|бьют|душать|душат|ріжуть|режут|тримають силою|держат силой)>"),
  re("<(погрожує|погрожують|угрожает|угрожают) (мені |мне )?(вбити|убить|ножем|ножом|зброєю|оружием|пістолетом|пистолетом)>"),
  re("<(мені (зараз )?небезпечно|мне (сейчас )?опасно)>"),
];

export function assessSafety(text: string): SafetyAssessment {
  const t = normalizeForMatching(text);
  const reasons = new Set<SafetyReason>();

  if (SELF_HARM.some((p) => p.test(t))) reasons.add("self_harm");
  if (IMMEDIATE_DANGER.some((p) => p.test(t))) reasons.add("immediate_danger");

  const harmVerb = HARM_VERB.test(t);
  const weapon = WEAPON.test(t);
  if (harmVerb && (weapon || PLAN.test(t))) reasons.add("harm_to_others");

  if (reasons.size > 0) return { level: "crisis", reasons: [...reasons] };
  // «Я його вбю» про начальника — зазвичай фігура мови. Механіки дозволені, але без руйнівних.
  if (harmVerb || weapon) return { level: "caution", reasons: [] };
  return { level: "none", reasons: [] };
}
