const NEGATIONS = ["не", "нет", "ни", "not"];
const SOFTENERS = ["дуже", "зовсім", "особливо", "сильно", "так", "очень", "совсем", "особо", "сильно", "то", "вже", "уже", "більше", "больше"];

/** «я не злюсь», «не дуже бісить», «уже не бесит». «Ні, мене бісить» — не заперечення. */
function negated(before: string): boolean {
  const w = before.trimEnd().split(" ");
  const last = w[w.length - 1] ?? "";
  const prev = w[w.length - 2] ?? "";
  return NEGATIONS.includes(last) || (SOFTENERS.includes(last) && NEGATIONS.includes(prev));
}

/** Позиції збігів початку слова/фрази. Фраза з «не» усередині не перевіряється на заперечення. */
function hits(t: string, stems: readonly string[]): number {
  let score = 0;
  for (const stem of stems) {
    const s = stem;
    let from = 0;
    for (;;) {
      const idx = t.indexOf(` ${s}`, from);
      if (idx < 0) break;
      from = idx + 1;
      if (!/^(не|ни|ні) /.test(s) && negated(t.slice(0, idx))) continue;
      score++;
      break;
    }
  }
  return score;
}

export function localRoute(text: string): LocalRoute {
  const t = normalizeForMatching(text);
  const specific = (Object.keys(SPECIFIC) as Specific[])
    .map((c) => ({ c: c as Category, s: hits(t, SPECIFIC[c]) }))
    .filter((x) => x.s > 0);

  const war = hits(t, WAR) > 0;
  let warMood: WarMood = null;
  if (war) {
    const grief = hits(t, GRIEF) > 0;
    const fear = hits(t, FEAR) > 0;
    const anger = hits(t, WAR_ANGER) > 0 || hits(t, WAR_HOSTILE) > 0;
    // Горе/страх важливіші за злість: карта — лише коли це справді злість.
    warMood = grief ? "grief" : fear ? "fear" : anger ? "anger" : null;
    if (warMood === "anger") specific.unshift({ c: "war_anger", s: 2 });
  }

  specific.sort((a, b) => b.s - a.s);
  let categories = specific.map((x) => x.c);
  if (warMood === "grief" && !categories.includes("unsaid_words") && /сказ|написа|попрощ/.test(t)) categories.unshift("unsaid_words");

  if (categories.length === 0) {
    if (warMood === "fear" || warMood === "grief") categories = ["general"];
    else if (hits(t, ANGER) > 0) categories = ["anger"];
    else if (hits(t, GENERAL) > 0) categories = ["general"];
  }

  const clarity: Clarity =
    war && warMood === null && categories.length === 0
      ? "unclear"
      : categories.length === 1
        ? "clear"
        : categories.length > 1
          ? "multiple"
          : "unclear";
  return {
    categories: categories.slice(0, 3),
    primary: clarity === "clear" ? categories[0]! : null,
    clarity,
    warMood: war ? warMood : null,
    war,
  };
}

/** Підказки для ручного вибору. */
export function keywordCategories(text: string): Category[] {
  return localRoute(text).categories;
}
