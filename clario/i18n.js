(() => {
  const STORE = "clario-lang";
  const textEls = [...document.querySelectorAll("[data-i18n]")];
  const attrEls = [...document.querySelectorAll("*")].filter((el) =>
    [...el.attributes].some((a) => a.name.startsWith("data-i18n-")));

  // Snapshot the Ukrainian source so we can switch back without reloading
  const uk = { title: document.title };
  textEls.forEach((el) => { uk[el.dataset.i18n] = el.innerHTML; });
  attrEls.forEach((el) => {
    [...el.attributes].forEach((a) => {
      if (a.name.startsWith("data-i18n-")) uk[a.value] = el.getAttribute(a.name.slice(10));
    });
  });

  const apply = (lang) => {
    const dict = lang === "en" ? CLARIO_EN : uk;
    textEls.forEach((el) => { const v = dict[el.dataset.i18n]; if (v != null) el.innerHTML = v; });
    attrEls.forEach((el) => {
      [...el.attributes].forEach((a) => {
        if (!a.name.startsWith("data-i18n-")) return;
        const v = dict[a.value];
        if (v != null) el.setAttribute(a.name.slice(10), v);
      });
    });
    document.title = dict.title;
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  };

  const fromUrl = new URLSearchParams(location.search).get("lang");
  let saved = null;
  try { saved = localStorage.getItem(STORE); } catch {}
  const initial = ["uk", "en"].includes(fromUrl) ? fromUrl : saved === "en" ? "en" : "uk";
  apply(initial);

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.dataset.lang;
      apply(lang);
      try { localStorage.setItem(STORE, lang); } catch {}
      const url = new URL(location.href);
      url.searchParams.delete("lang");
      history.replaceState(null, "", url);
    });
  });
})();
